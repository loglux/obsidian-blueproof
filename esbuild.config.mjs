import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import path from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// An import of "inline-worker:./x.worker.ts" bundles that file on its own and gives the text of its code, to start a Web Worker from (a
// plugin release holds main.js only, so the worker cannot be a file of its own). Used for the Hunspell dictionaries.
const inlineWorker = {
	name: 'inline-worker',
	setup(build) {
		build.onResolve({ filter: /^inline-worker:/ }, (args) => ({
			path: path.resolve(args.resolveDir, args.path.slice('inline-worker:'.length)),
			namespace: 'inline-worker',
		}));
		build.onLoad({ filter: /.*/, namespace: 'inline-worker' }, async (args) => {
			const result = await esbuild.build({
				entryPoints: [args.path],
				bundle: true,
				write: false,
				format: 'iife',
				target: 'es2021',
				minify: prod,
				platform: 'browser',
			});
			return { contents: `export default ${JSON.stringify(result.outputFiles[0].text)};`, loader: 'js' };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	plugins: [inlineWorker],
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	// fastText's WebAssembly and language model (src/prose/fasttext.ts) go into main.js as bytes: a release holds main.js only.
	loader: { '.wasm': 'binary', '.ftz': 'binary' },
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
